CREATE TABLE timezones (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text     NOT NULL,
    gmt_offset integer  NOT NULL,
    tz_name    text     NOT NULL UNIQUE,
    visible    smallint NOT NULL DEFAULT 0
);

CREATE TABLE channels (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id   text        NOT NULL UNIQUE,
    display_name text,
    category     text,
    area         text                 DEFAULT 'CN',
    logo_url     text,
    timezone     text        NOT NULL DEFAULT 'Asia/Shanghai'
                             REFERENCES timezones (tz_name) ON UPDATE CASCADE ON DELETE RESTRICT,
    is_active    smallint    NOT NULL DEFAULT 1,
    regexp       text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE channel_mappings (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_id          text             NOT NULL
                                           REFERENCES channels (channel_id) ON UPDATE CASCADE ON DELETE CASCADE,
    provider_id           text             NOT NULL,
    provider_channel_id   text             NOT NULL,
    provider_channel_name text,
    confidence            double precision NOT NULL DEFAULT 1,
    is_verified           smallint         NOT NULL DEFAULT 0,
    created_at            timestamptz      NOT NULL DEFAULT now(),
    updated_at            timestamptz      NOT NULL DEFAULT now(),
    UNIQUE (provider_id, provider_channel_id)
);

CREATE INDEX idx_channel_mappings_canonical_id ON channel_mappings (canonical_id);

CREATE TABLE programs (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id          text        NOT NULL
                                    REFERENCES channels (channel_id) ON UPDATE CASCADE ON DELETE CASCADE,
    title               text        NOT NULL,
    description         text,
    start_time          timestamptz NOT NULL,
    end_time            timestamptz NOT NULL,
    category            text,
    provider_id         text,
    provider_program_id text,
    original_timezone   text        NOT NULL DEFAULT 'Asia/Shanghai',
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_programs_channel_start ON programs (channel_id, start_time);
CREATE INDEX idx_programs_provider_start ON programs (provider_id, start_time);
CREATE INDEX idx_programs_end_time ON programs (end_time);

