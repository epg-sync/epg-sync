-- +goose Up
-- 自定义 XMLTV 数据源（.xml / .xml.gz），由管理后台维护。
-- mode：full 全量覆盖，某频道某天以文件为准，多个全量源冲突时先添加的（id 小的）优先，节目 provider_id 为 'custom:<id>'；
--       fill 增量补充，只补内置源和全量源当天都没有节目的「频道+天」，节目 provider_id 为 'custom-fill:<id>'。
-- priority 只对增量源有意义，数字越小优先级越高。
CREATE TABLE custom_sources (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text        NOT NULL,
    url           text        NOT NULL,
    mode          text        NOT NULL DEFAULT 'full' CHECK (mode IN ('full', 'fill')),
    enabled       smallint    NOT NULL DEFAULT 1,
    priority      integer     NOT NULL DEFAULT 100,
    last_sync_at  timestamptz,
    -- running / success / failed，从未同步过为空
    last_status   text        NOT NULL DEFAULT '',
    last_error    text        NOT NULL DEFAULT '',
    -- 同步成功时的补充说明，如因冲突跳过的频道日数
    last_message  text        NOT NULL DEFAULT '',
    program_count integer     NOT NULL DEFAULT 0,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

