-- 程序日志，供管理后台查看。stdout（docker logs）里的日志不变，这里是同一份日志的结构化副本。
-- 按 logger.retention_days 定期清理。
CREATE TABLE logs (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time    timestamptz NOT NULL,
    -- zap 的级别值：-1 debug、0 info、1 warn、2 error、3 dpanic、4 panic、5 fatal，按「不低于某级别」筛选
    level   smallint    NOT NULL,
    -- 日志来源：http（请求）、gorm（数据库），业务代码为空
    logger  text        NOT NULL DEFAULT '',
    caller  text        NOT NULL DEFAULT '',
    message text        NOT NULL,
    fields  jsonb,
    stack   text        NOT NULL DEFAULT ''
);

-- 列表按 id 倒序翻页；清理按 time
CREATE INDEX idx_logs_level_id ON logs (level, id);
CREATE INDEX idx_logs_time ON logs (time);

-- +goose Down
DROP TABLE logs;
